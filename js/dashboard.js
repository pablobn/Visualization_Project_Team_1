function corrColor(v) {
  if (v == null || isNaN(v)) return 'rgba(255,255,255,0.04)';
  const t = Math.max(-1, Math.min(1, v));
  const cool = { r: 77, g: 128, b: 235 };
  const white = { r: 230, g: 228, b: 222 };
  const warm = { r: 220, g: 65, b: 65 };
  let r, g, b;
  if (t < 0) {
    const k = 1 + t;
    r = Math.round(cool.r + (white.r - cool.r) * k);
    g = Math.round(cool.g + (white.g - cool.g) * k);
    b = Math.round(cool.b + (white.b - cool.b) * k);
  } else {
    const k = t;
    r = Math.round(white.r + (warm.r - white.r) * k);
    g = Math.round(white.g + (warm.g - white.g) * k);
    b = Math.round(white.b + (warm.b - white.b) * k);
  }
  return `rgb(${r}, ${g}, ${b})`;
}

function corrTextColor(v) {
  if (v == null || isNaN(v)) return 'var(--muted)';
  return Math.abs(v) > 0.45 ? '#ffffff' : '#0b1326';
}

function buildHeatmapTable(labels, matrix) {
  const headerCells = labels
    .map((l) => `<th class="heatmap-colhead"><span>${l}</span></th>`)
    .join('');

  const rows = matrix.map((row, i) => {
    const cells = row
      .map((v) => {
        if (v == null || isNaN(v)) {
          return `<td class="heatmap-cell heatmap-cell--empty">–</td>`;
        }
        const bg = corrColor(v);
        const fg = corrTextColor(v);
        return `<td class="heatmap-cell" style="background:${bg}; color:${fg};">${v.toFixed(2)}</td>`;
      })
      .join('');
    return `<tr><th class="heatmap-rowhead">${labels[i]}</th>${cells}</tr>`;
  }).join('');

  return `
    <table class="heatmap-table">
      <thead><tr><th></th>${headerCells}</tr></thead>
      <tbody>${rows}</tbody>
    </table>
  `;
}

function buildLiveCorrelation(kind, compoundKey) {
  const c = analysisData[compoundKey];
  const o = analysisData.outdoor;

  if (kind === 'temperature') {
    return correlationMatrix([
      ['Heating', c.heating],
      ['Lower', c.temperature.bottom],
      ['Middle', c.temperature.middle],
      ['Upper', c.temperature.top],
      ['Outside', o.temperature]
    ]);
  }
  return correlationMatrix([
    ['Lower', c.humidity.bottom],
    ['Middle', c.humidity.middle],
    ['Upper', c.humidity.top],
    ['Outside', o.humidity]
  ]);
}

function renderHeatmap(containerId, kind, compoundKey) {
  const root = document.getElementById(containerId);
  if (!root) return;
  const { labels, matrix } = buildLiveCorrelation(kind, compoundKey);
  root.innerHTML = buildHeatmapTable(labels, matrix);
}

function renderCorrelationBlock(compoundKey) {
  renderHeatmap('heatmap-temp', 'temperature', compoundKey);
  renderHeatmap('heatmap-hum', 'moisture', compoundKey);
}


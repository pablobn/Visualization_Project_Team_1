function pearson(a, b) {
  const n = Math.min(a.length, b.length);
  let sx = 0, sy = 0, sxx = 0, syy = 0, sxy = 0, k = 0;
  for (let i = 0; i < n; i++) {
    const x = a[i], y = b[i];
    if (x == null || y == null || isNaN(x) || isNaN(y)) continue;
    sx += x; sy += y;
    sxx += x * x; syy += y * y;
    sxy += x * y;
    k++;
  }
  if (k < 2) return null;
  const num = k * sxy - sx * sy;
  const den = Math.sqrt((k * sxx - sx * sx) * (k * syy - sy * sy));
  if (den === 0 || !isFinite(den)) return null;
  return num / den;
}

function correlationMatrix(seriesEntries) {
  const labels = seriesEntries.map(([name]) => name);
  const arrays = seriesEntries.map(([, arr]) => sliceRange(arr));
  const n = labels.length;
  const matrix = [];
  for (let i = 0; i < n; i++) {
    const row = [];
    for (let j = 0; j < n; j++) {
      row.push(i === j ? 1 : pearson(arrays[i], arrays[j]));
    }
    matrix.push(row);
  }
  return { labels, matrix };
}


let monthBuckets = [];

function buildPickerBuckets() {
  weekBuckets = [];
  monthBuckets = [];
  if (!analysisData.labels.length) return;

  const monthsMap = new Map();
  analysisData.labels.forEach((iso, i) => {
    const key = iso.slice(0, 7);
    if (!monthsMap.has(key)) monthsMap.set(key, { start: i, end: i });
    else monthsMap.get(key).end = i;
  });
  for (const [key, b] of monthsMap) {
    const [y, m] = key.split('-').map(Number);
    const label = new Date(Date.UTC(y, m - 1, 1))
      .toLocaleString('en', { month: 'long', year: 'numeric' });
    monthBuckets.push({ key, label, start: b.start, end: b.end });
  }

  let currentKey = null;
  let current = null;
  analysisData.labels.forEach((iso, i) => {
    const [y, m, d] = iso.split('-').map(Number);
    const date = new Date(Date.UTC(y, m - 1, d));
    const dayOfWeek = date.getUTCDay();
    const offset = (dayOfWeek + 6) % 7;
    const monday = new Date(date);
    monday.setUTCDate(date.getUTCDate() - offset);
    const weekKey = monday.toISOString().slice(0, 10);
    if (weekKey !== currentKey) {
      currentKey = weekKey;
      const month = monday.toLocaleString('en', { month: 'short' });
      const label = `Week of ${month} ${monday.getUTCDate()}, '${String(monday.getUTCFullYear()).slice(2)}`;
      current = { key: weekKey, label, start: i, end: i };
      weekBuckets.push(current);
    } else {
      current.end = i;
    }
  });
}

